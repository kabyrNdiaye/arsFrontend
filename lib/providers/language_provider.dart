class LanguageProvider extends ChangeNotifier {
  String _currentLanguage = 'fr';
  static const String _langKey = 'selected_language';
  
  String get currentLanguage => _currentLanguage;
  
  LanguageProvider() {
    _loadLanguage();
  }

  Future<void> _loadLanguage() async {
    final prefs = await SharedPreferences.getInstance();
    _currentLanguage = prefs.getString(_langKey) ?? 'fr';
    notifyListeners();
  }
  
  // Obtenir le nom de la langue affichée
  String get languageName {
    switch (_currentLanguage) {
      case 'fr':
        return 'Français';
      case 'en':
        return 'English';
      case 'es':
        return 'Español';
      default:
        return 'Français';
    }
  }
  
  Future<void> setLanguage(String languageCode) async {
    _currentLanguage = languageCode;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_langKey, languageCode);
    notifyListeners();
  }
  
  // Méthode pour obtenir une traduction
  String translate(String key) {
    return _translations[_currentLanguage]?[key] ?? _translations['fr']?[key] ?? key;
  }
  
